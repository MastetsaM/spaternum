-- Notes with recordings (2026-11-22): recordings belong to a note; title and tags are the note's.
-- Spec: planning/specs/notes-recordings_spec.md
-- Replaces the voice_notes module. A database that has voice notes gets them converted:
-- a "Voice notes" folder, one note per voice note, its recording in that note. A fresh
-- database (no voice_notes table) only gets the new table.

CREATE SEQUENCE note_recordings_seq;

CREATE TABLE note_recordings (
    id          uuid PRIMARY KEY,              -- generated by the client; also the audio file name
    note_id     uuid NOT NULL,                 -- no foreign key: a recording can arrive before its note
    recorded_at timestamptz NOT NULL,          -- when recording started
    duration_ms integer NOT NULL,
    size_bytes  bigint NOT NULL,               -- size of the local file; the upload is checked against it
    mime_type   text NOT NULL,                 -- 'audio/webm;codecs=opus'
    uploaded_at timestamptz,                   -- set by the SERVER when the file is stored; NULL = not uploaded yet
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,          -- latest write wins
    archived_at timestamptz,                   -- NULL = active
    seq         bigint NOT NULL                -- server-assigned on every write; sync pulls by this
);

CREATE INDEX note_recordings_seq_idx ON note_recordings (seq);
CREATE INDEX note_recordings_note_idx ON note_recordings (note_id);
CREATE TRIGGER note_recordings_notify AFTER INSERT OR UPDATE ON note_recordings
    FOR EACH STATEMENT EXECUTE FUNCTION sync_notify();

DO $$
DECLARE
    folder uuid := gen_random_uuid();
BEGIN
    -- Two steps: the second query would fail to plan if the table didn't exist
    IF to_regclass('voice_notes') IS NULL THEN
        RETURN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM voice_notes) THEN
        DROP TABLE voice_notes;
        DROP SEQUENCE voice_notes_seq;
        RETURN;
    END IF;

    INSERT INTO note_folders (id, parent_id, name, created_at, updated_at, archived_at, seq)
    VALUES (folder, NULL, 'Voice notes', now(), now(), NULL, nextval('note_folders_seq'));

    -- One new note id per voice note (a volatile default is computed for each row)
    ALTER TABLE voice_notes ADD COLUMN note_id uuid NOT NULL DEFAULT gen_random_uuid();

    -- Archived voice notes become an archived note and recording with the same archived_at,
    -- so restoring the note brings its recording back.
    INSERT INTO notes (id, folder_id, title, body, tags, pinned,
                       created_at, updated_at, archived_at, seq)
    SELECT note_id, folder, title, '', tags, false,
           created_at, updated_at, archived_at, nextval('notes_seq')
    FROM voice_notes ORDER BY seq;

    INSERT INTO note_recordings (id, note_id, recorded_at, duration_ms, size_bytes, mime_type,
                                 uploaded_at, created_at, updated_at, archived_at, seq)
    SELECT id, note_id, recorded_at, duration_ms, size_bytes, mime_type,
           uploaded_at, created_at, updated_at, archived_at, nextval('note_recordings_seq')
    FROM voice_notes ORDER BY seq;

    DROP TABLE voice_notes;
    DROP SEQUENCE voice_notes_seq;
END $$;
