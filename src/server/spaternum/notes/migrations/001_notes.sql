-- Notes module: folders (any depth) and Markdown notes. Spec: planning/specs/notes_spec.md
-- No foreign keys: after being offline, devices push folders and notes separately, in no
-- fixed order, so a note can arrive before its folder.

CREATE SEQUENCE note_folders_seq;

CREATE TABLE note_folders (
    id          uuid PRIMARY KEY,                  -- generated by the client
    parent_id   uuid,                              -- NULL = top level
    name        text NOT NULL,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,              -- latest write wins
    archived_at timestamptz,                       -- NULL = active
    seq         bigint NOT NULL                    -- server-assigned on every write; sync pulls by this
);

CREATE INDEX note_folders_seq_idx ON note_folders (seq);
CREATE INDEX note_folders_parent_idx ON note_folders (parent_id);
CREATE TRIGGER note_folders_notify AFTER INSERT OR UPDATE ON note_folders
    FOR EACH STATEMENT EXECUTE FUNCTION sync_notify();

CREATE SEQUENCE notes_seq;

CREATE TABLE notes (
    id          uuid PRIMARY KEY,                  -- generated by the client
    folder_id   uuid,                              -- NULL = no folder
    body        text NOT NULL DEFAULT '',          -- Markdown; first line = title
    tags        text[] NOT NULL DEFAULT '{}',
    pinned      boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,              -- latest write wins
    archived_at timestamptz,                       -- NULL = active
    seq         bigint NOT NULL                    -- server-assigned on every write; sync pulls by this
);

CREATE INDEX notes_seq_idx ON notes (seq);
CREATE INDEX notes_folder_idx ON notes (folder_id);
CREATE INDEX notes_tags_idx ON notes USING gin (tags);
CREATE TRIGGER notes_notify AFTER INSERT OR UPDATE ON notes
    FOR EACH STATEMENT EXECUTE FUNCTION sync_notify();
