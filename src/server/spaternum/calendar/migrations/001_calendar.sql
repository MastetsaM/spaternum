-- Calendar module: one-off events, repeating events (series) and their exceptions, all in one
-- table. Spec: planning/specs/calendar_spec.md
-- No foreign keys: after being offline, a device can push an exception before its series.

CREATE SEQUENCE calendar_events_seq;

CREATE TABLE calendar_events (
    id             uuid PRIMARY KEY,               -- generated by the client
    title          text NOT NULL,
    notes          text NOT NULL DEFAULT '',       -- free text under the event
    all_day        boolean NOT NULL DEFAULT false,
    start_at       timestamptz NOT NULL,
    end_at         timestamptz NOT NULL,           -- after start_at; checked by the app, not here
    time_zone      text NOT NULL,                  -- IANA name, e.g. 'Europe/Lisbon'
    rrule          text,                           -- NULL = one-off; e.g. 'FREQ=WEEKLY;BYDAY=MO'
    series_id      uuid,                           -- set on an exception: the series it changes
    original_start timestamptz,                    -- set on an exception: which occurrence it replaces
    cancelled      boolean NOT NULL DEFAULT false, -- exception that removes one occurrence
    created_at     timestamptz NOT NULL,
    updated_at     timestamptz NOT NULL,           -- latest write wins
    archived_at    timestamptz,                    -- NULL = active
    seq            bigint NOT NULL                 -- server-assigned on every write; sync pulls by this
);

CREATE INDEX calendar_events_seq_idx ON calendar_events (seq);
CREATE INDEX calendar_events_series_idx ON calendar_events (series_id);
CREATE TRIGGER calendar_events_notify AFTER INSERT OR UPDATE ON calendar_events
    FOR EACH STATEMENT EXECUTE FUNCTION sync_notify();
