-- Voice notes: one row per recording; the audio is a file at DATA_DIR/audio/<id>.webm,
-- uploaded separately. Spec: planning/specs/voice-notes_spec.md

CREATE SEQUENCE voice_notes_seq;

CREATE TABLE voice_notes (
    id          uuid PRIMARY KEY,              -- generated by the client; also the audio file name
    title       text NOT NULL DEFAULT '',      -- optional; typed by Mihail and/or set by processing in phase 2
    tags        text[] NOT NULL DEFAULT '{}',
    recorded_at timestamptz NOT NULL,          -- when recording started
    duration_ms integer NOT NULL,
    size_bytes  bigint NOT NULL,               -- size of the local file; the upload is checked against it
    mime_type   text NOT NULL,                 -- 'audio/webm;codecs=opus'
    uploaded_at timestamptz,                   -- set by the SERVER when the file is stored; NULL = not uploaded yet
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,          -- latest write wins
    archived_at timestamptz,                   -- NULL = active
    seq         bigint NOT NULL                -- server-assigned on every write; sync pulls by this
);

CREATE INDEX voice_notes_seq_idx ON voice_notes (seq);
CREATE INDEX voice_notes_tags_idx ON voice_notes USING gin (tags);
CREATE TRIGGER voice_notes_notify AFTER INSERT OR UPDATE ON voice_notes
    FOR EACH STATEMENT EXECUTE FUNCTION sync_notify();
